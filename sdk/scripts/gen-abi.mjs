// Regenerates src/abi.ts from forge artifacts. Run `forge build` in the repo root first.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const core = JSON.parse(readFileSync(join(root, 'out/MADBountyCore.sol/MADBountyCore.json'), 'utf8'));
const erc20Abi = [
  { type: 'function', name: 'approve', stateMutability: 'nonpayable', inputs: [{ name: 'spender', type: 'address' }, { name: 'amount', type: 'uint256' }], outputs: [{ type: 'bool' }] },
  { type: 'function', name: 'allowance', stateMutability: 'view', inputs: [{ name: 'owner', type: 'address' }, { name: 'spender', type: 'address' }], outputs: [{ type: 'uint256' }] },
  { type: 'function', name: 'balanceOf', stateMutability: 'view', inputs: [{ name: 'who', type: 'address' }], outputs: [{ type: 'uint256' }] },
  { type: 'function', name: 'decimals', stateMutability: 'view', inputs: [], outputs: [{ type: 'uint8' }] },
];
const out = `// AUTO-GENERATED by scripts/gen-abi.mjs from out/MADBountyCore.sol/MADBountyCore.json. Do not edit.
export const madBountyCoreAbi = ${JSON.stringify(core.abi, null, 2)} as const;

export const erc20Abi = ${JSON.stringify(erc20Abi, null, 2)} as const;
`;
writeFileSync(join(root, 'sdk/src/abi.ts'), out);
console.log(`wrote sdk/src/abi.ts (${core.abi.length} core entries)`);
